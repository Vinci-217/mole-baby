#!/usr/bin/env python3
"""Build a paginated, GitHub-readable index of all tracked image assets.

Run from any directory after adding new assets to Git's index. The gallery only
covers files tracked by Git; ignored and untracked working files are excluded.
"""
from __future__ import annotations

import html
import subprocess
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
GALLERY = ROOT / 'gallery'
PAGES = GALLERY / 'pages'
MARKER = '<!-- Generated by scripts/generate-asset-gallery.py. Do not edit. -->'
PAGE_SIZE = 24
EXTENSIONS = {'.gif', '.png', '.jpg', '.jpeg', '.webp', '.svg', '.ico', '.icns'}
PREVIEWABLE = {'.gif', '.png', '.jpg', '.jpeg', '.webp', '.svg'}
LATEST = [
    ('变身魔术 · 小兔子', 'artifacts/transform-preview/rabbit.gif'),
    ('变身魔术 · 小鸟', 'artifacts/transform-preview/bird.gif'),
    ('变身魔术 · 小树', 'artifacts/transform-preview/tree.gif'),
    ('旋风术', 'artifacts/spell-preview/wind.gif'),
    ('流火术', 'artifacts/spell-preview/fire.gif'),
    ('寒冰术', 'artifacts/spell-preview/ice.gif'),
    ('陨石术', 'artifacts/spell-preview/meteor.gif'),
]
GROUPS = [
    ('animations', '历史动画', '项目中已跟踪的其他 GIF，包括应用内动作、历史方案与原素材。'),
    ('game', '游戏图片素材', '游戏使用的角色、场景、道具、界面、图集与图标。'),
    ('references', '设计参考和其他图片', '设计参考板、历史预览与其他已跟踪图片；部分是精灵图，并非独立动画。'),
]


def link(path: str, prefix: str) -> str:
    # URL-encode spaces, Chinese, #, ?, and parentheses without encoding path separators.
    return prefix + quote(path, safe='/')


def tracked_images() -> list[str]:
    raw = subprocess.check_output(['git', '-C', str(ROOT), 'ls-files', '-z'])
    paths = [p.decode('utf-8', errors='surrogateescape') for p in raw.split(b'\0') if p]
    return sorted(p for p in paths if Path(p).suffix.lower() in EXTENSIONS and not p.startswith('gallery/'))


def recent_images(paths: list[str]) -> list[str]:
    # Most recently changed tracked images, across the checked-out history.
    raw = subprocess.check_output(['git', '-C', str(ROOT), 'log', '-30', '--format=',
                                   '--name-only', '--diff-filter=AM', '-z'])
    available = set(paths)
    recent = []
    for part in raw.split(b'\0'):
        candidate = part.decode('utf-8', errors='surrogateescape').strip('\n')
        if candidate in available and candidate not in recent:
            recent.append(candidate)
        if len(recent) == 12:
            break
    return recent


def categorize(paths: list[str]) -> dict[str, list[str]]:
    result = {key: [] for key, _, _ in GROUPS}
    latest = {path for _, path in LATEST}
    for path in paths:
        if path in latest:
            continue
        if Path(path).suffix.lower() == '.gif':
            result['animations'].append(path)
        elif path.startswith('public/'):
            result['game'].append(path)
        else:
            result['references'].append(path)
    return result


def item(path: str) -> str:
    url = link(path, '../../')
    display = html.escape(path)
    if Path(path).suffix.lower() not in PREVIEWABLE:
        return f'- <a href="{url}"><code>{display}</code></a>（图标文件，点击下载查看）\n'
    return (f'### <code>{display}</code>\n\n'
            f'<a href="{url}"><img src="{url}" alt="{display}" width="180"></a>\n\n'
            f'[查看原图]({url})\n\n')


def make_pages(key: str, title: str, paths: list[str]) -> list[str]:
    chunks = [paths[i:i+PAGE_SIZE] for i in range(0, len(paths), PAGE_SIZE)]
    page_names = [f'{key}-{i:03d}.md' for i in range(1, len(chunks)+1)]
    for index, (name, chunk) in enumerate(zip(page_names, chunks)):
        nav = ['[返回素材首页](../README.md)']
        if index:
            nav.append(f'[上一页]({page_names[index-1]})')
        if index+1 < len(chunks):
            nav.append(f'[下一页]({page_names[index+1]})')
        content = [MARKER, f'# {title} · {index+1}/{len(chunks)}', '', ' · '.join(nav),
                   '', f'本页 {len(chunk)} 个文件，点击图片或「查看原图」可打开原文件。', '']
        content += [item(p) for p in chunk]
        content += [' · '.join(nav), '']
        (PAGES / name).write_text('\n'.join(content), encoding='utf-8')
    return page_names


def main() -> None:
    paths = tracked_images()
    groups = categorize(paths)
    PAGES.mkdir(parents=True, exist_ok=True)
    # Only remove pages produced by this script, leaving unrelated files alone.
    for path in PAGES.glob('*.md'):
        if path.read_text(encoding='utf-8').startswith(MARKER):
            path.unlink()
    rows = [MARKER, '# 拉姆动画和图片素材预览', '',
            '这个分支用于审阅素材。这里列出分支中 **Git 已跟踪** 的 GIF、PNG、JPG、WebP、SVG 和图标文件；提交新素材后自动更新索引，也可以手动运行 `python scripts/generate-asset-gallery.py`。',
            '', '## 最新预览：变身魔术和四系法术', '',
            '变身魔术是新绘的候选：原拉姆在同一位置变成小兔、小鸟或小树后恢复，关键姿态由图片模型绘制，切换和停顿由程序编排；随机触发尚未接入游戏。四系法术仍使用原角色静态图和各 4 张新绘关键姿态。参考同系列游戏视觉，未核实《摩尔勇士》完整技能原帧，不能视为官方动作复刻。', '']
    for title, path in LATEST:
        if path in paths:
            url = link(path, '../')
            rows += [f'### {title}', '', f'![{title}]({url})', '', f'[打开 GIF 原文件]({url})', '']
    recent = recent_images(paths)
    if recent:
        rows += ['## 最近更新素材', '', *[f'- [{html.escape(path)}]({link(path, "../")})' for path in recent], '']
    rows += ['## 全部素材分类', '', f'共 {len(paths)} 个已跟踪图片文件。每页最多 {PAGE_SIZE} 项，按路径排序。', '']
    for key, title, description in GROUPS:
        page_names = make_pages(key, title, groups[key])
        rows += [f'### {title}（{len(groups[key])}）', '', description, '']
        if page_names:
            rows += [' · '.join(f'[第 {i} 页](pages/{name})' for i, name in enumerate(page_names, 1)), '']
        else:
            rows += ['暂无素材。', '']
    rows += ['## 其他说明', '',
             '[项目现有动画说明](../README.md#全部现有动画全部展开) · [本次预览说明](../research/spell-redraw-preview.md) · [参考与画风记录](../skills/mole-classic-art/references/spell-animation-guide.md)', '']
    (GALLERY / 'README.md').write_text('\n'.join(rows), encoding='utf-8')
    print(f'已索引 {len(paths)} 个图片文件；生成 {sum((len(v)+PAGE_SIZE-1)//PAGE_SIZE for v in groups.values())} 个分页。')


if __name__ == '__main__':
    main()
