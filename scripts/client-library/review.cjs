'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('@playwright/test');
const root=path.resolve(__dirname,'../..'),out=path.join(root,'artifacts/restaurant-loop');
const url=process.argv[2]||'http://127.0.0.1:5181';
let browser;
(async()=>{
 fs.mkdirSync(out,{recursive:true});
 browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/local/bin/chromium',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(url);
 await page.locator('#files').filter({hasText:'21,523'}).waitFor();
 await page.locator('#demo summary').click();
 await page.locator('#demo-video').evaluate(video=>video.play());
 await page.waitForFunction(()=>document.querySelector('video').currentTime>0.2);
 const video=await page.locator('#demo-video').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,duration:v.duration,time:v.currentTime,paused:v.paused,error:v.error?.message||null}));
 assert.equal(video.duration,11);assert.equal(video.error,null);assert.equal(video.paused,false);
 await page.locator('[data-movie="restaurant-loop.mp4"]').click();
 await page.waitForFunction(()=>document.querySelector('video').videoWidth===960);
 await page.locator('#query').fill('1200042');
 await page.locator('#search').evaluate(form=>form.requestSubmit());
 const source='root/resource/petcloth/swf2/1200042.swf';
 await page.locator(`[data-path="${source}"]`).click();
 const sourceResponse=await page.request.get(url+'/api/asset?'+new URLSearchParams({path:source}));
 const sourceData=await sourceResponse.json();
 const timeline=sourceData.timeline.timelines.find(t=>t.labels.some(l=>l.name==='down'));
 const frame=timeline.labels.find(l=>l.name==='down').frame;
 await page.locator(`[data-sprite="${timeline.sprite}"][data-frame="${frame}"]`).click();
 await page.waitForFunction(()=>document.querySelector('#preview img')?.naturalWidth>0,{},{timeout:120000});
 const request={path:source,sprite:timeline.sprite,frame};
 const first=await(await page.request.post(url+'/api/preview',{data:request})).json();
 const second=await(await page.request.post(url+'/api/preview',{data:request})).json();
 assert.equal(first.state,'ready');assert.equal(first.key,second.key);assert.equal(first.url,second.url);
 const invalid=await page.request.post(url+'/api/preview',{data:{...request,path:'../outside.swf'}});
 assert.equal(invalid.status(),400);
 await page.screenshot({path:path.join(out,'asset-library.png'),fullPage:true});
 const mobile=[];
 for(const width of [390,360]){
  await page.setViewportSize({width,height:844});
  const dimensions=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
  assert.equal(dimensions.width,dimensions.scrollWidth);mobile.push(dimensions);
 }
 await page.screenshot({path:path.join(out,'asset-library-mobile.png'),fullPage:true});
 await page.locator('#query').fill('');await page.locator('#kind').selectOption('mp3');
 await page.locator('#search').evaluate(form=>form.requestSubmit());
 await page.locator('#total').filter({hasText:'159 个素材'}).waitFor();
 await page.locator('.item').first().click();
 await page.locator('audio').evaluate(audio=>{audio.muted=true;return audio.play()});
 await page.waitForFunction(()=>document.querySelector('audio')?.currentTime>0.1);
 const audio=await page.locator('audio').evaluate(a=>({duration:a.duration,playing:!a.paused,error:a.error?.message||null}));
 assert.ok(audio.duration>0);assert.equal(audio.playing,true);assert.equal(audio.error,null);
 assert.deepEqual(errors,[]);
 const result={video,fullSceneVideoLoaded:true,audio,source:sourceData.asset.path,cachedPreview:first,mobile,unknownSourceRejected:true,pageErrors:errors};
 fs.writeFileSync(path.join(out,'browser-checks.json'),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result,null,2));
})().catch(error=>{console.error(error);process.exitCode=1}).finally(async()=>{await browser?.close()});
